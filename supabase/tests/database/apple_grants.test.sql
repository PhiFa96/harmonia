begin;
create extension if not exists pgtap with schema extensions;
select plan(10);
select ok(not has_table_privilege('authenticated','public.apple_grants','SELECT'),'Client cannot read provider credentials');
select ok(not has_function_privilege('authenticated','public.read_apple_grant(uuid)','EXECUTE'),'Client cannot decrypt provider credentials');
select ok(not has_function_privilege('anon','public.save_apple_grant(uuid,text)','EXECUTE'),'Anonymous credential insertion denied');
insert into auth.users(id,email) values ('70000000-0000-4000-8000-000000000001','apple-grant-fixture@example.test');
set local role service_role;
select lives_ok($$select public.save_apple_grant('70000000-0000-4000-8000-000000000001','synthetic-refresh-first')$$,'Service saves verified credential');
select is(public.read_apple_grant('70000000-0000-4000-8000-000000000001'),'synthetic-refresh-first','Service decrypts its selected credential');
select lives_ok($$select public.save_apple_grant('70000000-0000-4000-8000-000000000001','synthetic-refresh-rotated')$$,'Rotation replaces credential');
select is(public.read_apple_grant('70000000-0000-4000-8000-000000000001'),'synthetic-refresh-rotated','Rotation is retained');
reset role;
select isnt((select v.secret from vault.secrets v join public.apple_grants g on g.secret_id=v.id where g.user_id='70000000-0000-4000-8000-000000000001'),'synthetic-refresh-rotated','Vault does not store cleartext');
create temporary table test_apple_secret as select secret_id from public.apple_grants where user_id='70000000-0000-4000-8000-000000000001';
delete from auth.users where id='70000000-0000-4000-8000-000000000001';
select is((select count(*) from public.apple_grants where user_id='70000000-0000-4000-8000-000000000001'),0::bigint,'Account deletion cascades credential reference');
select is((select count(*) from vault.secrets where id in (select secret_id from test_apple_secret)),0::bigint,'Account deletion also removes encrypted Vault secret');
select * from finish();
rollback;
