export type SchoolTextKey = keyof typeof de;
export function schoolText(
  locale: AppLocale,
  key: SchoolTextKey,
  values: Record<string, string | number> = {},
) {
  return SCHOOL_DRAFT_MESSAGES[locale][key].replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    String(values[name] ?? `{{${name}}}`),
  );
}
