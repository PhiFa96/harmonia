export const QUIZ_MESSAGES = { de, 'en-US': en, 'en-GB': { ...en } };
export type QuizTextKey = keyof typeof de;
export function quizText(
  locale: AppLocale,
  key: QuizTextKey,
  values: Record<string, string | number> = {},
) {
  return QUIZ_MESSAGES[locale][key].replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    String(values[name] ?? `{{${name}}}`),
  );
}
