export type LicenseTextKey = keyof typeof de;
export function licenseText(
  locale: AppLocale,
  key: LicenseTextKey,
  values: Record<string, string | number> = {},
) {
  return LICENSE_MESSAGES[locale][key].replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    String(values[name] ?? `{{${name}}}`),
  );
}
